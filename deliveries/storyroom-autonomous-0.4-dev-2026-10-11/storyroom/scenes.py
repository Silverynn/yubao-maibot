class SceneFeatures:
    def scene_view(self, db, room):
        self.sync_scene(db,room)
        row=dict(db.execute('SELECT * FROM scenes WHERE room=?',(room,)).fetchone())
        return {k:v for k,v in row.items() if k!='job'}

    def sync_scene(self, db, room):
        state=self.room(db,room);runtime=self.ensure_runtime(db,room)
        old=db.execute('SELECT * FROM scenes WHERE room=?',(room,)).fetchone()
        if old and old['node']==state['node'] and old['branch']==runtime['branch']:
            if old['status'] in ('held','queued') and (self.root/'scene-assets'/(old['hash']+'.png')).is_file():
                db.execute("UPDATE scenes SET status=?,image=?,job='' WHERE room=?",('ready' if runtime['state']=='RUNNING' else 'held','/api/scene-assets/'+old['hash']+'.png',room))
            return
        node=self.story(state)['nodes'][state['node']]
        prompt='横向场景背景，没有玩家人物，没有文字。统一二次元冒险插画风格。公开场景：'+node['title']+'。'+node['description']
        content_hash=hashlib.sha256(prompt.encode()).hexdigest()
        cached=(self.root/'scene-assets'/(content_hash+'.png')).is_file()
        db.execute('INSERT OR REPLACE INTO scenes VALUES(?,?,?,?,?,?,?,?,?,?)',
            (room,runtime['branch'],state['node'],uuid.uuid4().hex,prompt,
             '/api/scene-assets/'+content_hash+'.png' if cached else '',
             'ready' if cached else 'queued' if getattr(self,'image_configured',False) else 'unconfigured',
             '',content_hash,''))

    def claim_scene(self):
        with self.db() as db:
            for room in self.list_rooms():self.sync_scene(db,room['id'])
            for row in db.execute("SELECT s.* FROM scenes s JOIN runtime r ON r.room=s.room WHERE s.status='queued' AND r.enabled=1 AND r.state='RUNNING'").fetchall():
                count=db.execute('SELECT image_calls FROM runtime WHERE room=?',(row['room'],)).fetchone()[0]
                if count>=20:
                    db.execute("UPDATE scenes SET status='failed',error='本房间图片调用上限20次' WHERE room=?",(row['room'],))
                    continue
                job=uuid.uuid4().hex
                db.execute("UPDATE scenes SET status='generating',job=? WHERE room=?",(job,row['room']))
                db.execute('UPDATE runtime SET image_calls=image_calls+1 WHERE room=?',(row['room'],))
                runtime=self.ensure_runtime(db,row['room'])
                return {**dict(row),'job':job,'epoch':runtime['epoch']}
        return None

    def scene_current(self, ticket):
        with self.db() as db:
            r=self.ensure_runtime(db,ticket['room'])
            row=db.execute('SELECT job,revision FROM scenes WHERE room=?',(ticket['room'],)).fetchone()
            return row and row['job']==ticket['job'] and row['revision']==ticket['revision'] and r['state']=='RUNNING' and r['epoch']==ticket['epoch'] and r['branch']==ticket['branch']

    def complete_scene(self, ticket, encoded):
        # Store generated bytes only; no remote URL downloads or arbitrary file names.
        try:data=base64.b64decode(encoded,validate=True)
        except (ValueError,TypeError):fail('图片响应不是合法base64')
        if len(data)>8_000_000 or not data.startswith(b'\x89PNG\r\n\x1a\n'):
            fail('仅接受不超过8MB的PNG背景')
        from PIL import Image
        import io
        with Image.open(io.BytesIO(data)) as image:
            if image.width*image.height>16_000_000:fail('图片像素过多')
            image.verify()
        directory=self.root/'scene-assets';directory.mkdir(exist_ok=True)
        target=directory/(ticket['hash']+'.png')
        temp=target.with_suffix('.'+uuid.uuid4().hex+'.tmp');temp.write_bytes(data);temp.replace(target)
        with self.db() as db:
            row=db.execute('SELECT * FROM scenes WHERE room=?',(ticket['room'],)).fetchone();r=self.ensure_runtime(db,ticket['room'])
            if not row or row['job']!=ticket['job'] or row['branch']!=r['branch'] or row['revision']!=ticket['revision']:
                return {'cached':True,'displayed':False}
            running=r['state']=='RUNNING' and r['epoch']==ticket['epoch']
            db.execute("UPDATE scenes SET status=?,image=?,job='' WHERE room=?",('ready' if running else 'held','/api/scene-assets/'+ticket['hash']+'.png',ticket['room']))
        return {'cached':True,'displayed':running}


async def run_images(store, config):
    async def generate(ticket):
        async with httpx.AsyncClient(timeout=120,follow_redirects=False,trust_env=False) as client:
            response=await client.post(config['base_url'].rstrip('/')+'/images/generations',headers={'Authorization':'Bearer '+config['api_key']},
                json={'model':config['model'],'prompt':ticket['prompt'],'size':config.get('size','1536x1024'),'n':1,'response_format':'b64_json'})
            response.raise_for_status()
            return response.json()['data'][0]['b64_json']
    while True:
        ticket=store.claim_scene()
        if ticket:
            job=asyncio.create_task(generate(ticket))
            try:
                while not job.done():
                    await asyncio.sleep(.25)
                    if not store.scene_current(ticket):
                        job.cancel()
                        with store.db() as db:
                            db.execute("UPDATE scenes SET status='queued',job='' WHERE room=? AND job=?",(ticket['room'],ticket['job']))
                        break
                if not job.cancelled() and store.scene_current(ticket):
                    store.complete_scene(ticket,await job)
            except asyncio.CancelledError:raise
            except Exception as error:
                with store.db() as db:
                    db.execute("UPDATE scenes SET status='failed',error=?,job='' WHERE room=? AND job=?",('生成失败：'+type(error).__name__,ticket['room'],ticket['job']))
            finally:
                if not job.done():job.cancel()
                await asyncio.gather(job,return_exceptions=True)
        await asyncio.sleep(1)
